def ref(c,n,a,b,s):
 e=dict(path=books[n],start_line=a,end_line=b,supports=s,kind='原文')
 if not any(x['path']==e['path'] and x['start_line']==a and x['end_line']==b for x in c['evidence']):c['evidence'].append(e)
def series(c):
 if '卫斯理系列' not in c['series']:c['series'].append('卫斯理系列')
def ability(c,n,m,apps,limits):
 a=dict(name=n,type='技能',mechanism=m,visual='以声音、姿势、动作和可观察结果表现；不附加无证光效。',applications=apps,limits=limits)
 old=next((i for i,x in enumerate(c['abilities']) if x['name']==n),None)
 if old is None:c['abilities'].append(a)
 else:c['abilities'][old]=a
def uncertainty(c,s):
 if s not in c['uncertainties']:c['uncertainties'].append(s)
def trigger(c,s,cond,act):
 t=dict(situation=s,condition=cond,action=act)
 old=next((i for i,x in enumerate(c['logic']['triggers']) if x['situation']==s),None)
 if old is None:c['logic']['triggers'].append(t)
 else:c['logic']['triggers'][old]=t
def weak(n,m,v,d,mit):return dict(name=n,mechanism=m,visible=v,discovery=d,mitigation=mit)

